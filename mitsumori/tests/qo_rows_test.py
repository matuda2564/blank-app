"""見積⇔発注: 表に型式の列が無く、品名の欄(2行目)に型番がある書類でも、型式と数量・単価・金額を取れること。"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import mc_core as C

def L(y, toks):
    return {"page": 0, "text": " ".join(t for t, _, _ in toks), "x0": toks[0][1], "y0": y, "x1": toks[-1][2], "y1": y + 10, "src": "text", "toks": toks}

hdr = L(100, [("メーカー・品名", 10, 90), ("数", 300, 310), ("量", 318, 328), ("単位", 350, 370), ("単", 400, 410), ("価", 418, 428), ("金", 470, 480), ("額", 488, 498)])
r1 = L(120, [("1", 10, 15), ("国際チャート", 20, 90), ("記録紙", 95, 130)])
r2 = L(130, [("B9565AW-T", 20, 100), ("(18,500)", 110, 160)])
r3 = L(140, [("受注後14日", 20, 80), ("1", 305, 312), ("13,875", 395, 425), ("13,875", 470, 500)])
sh = L(160, [("送料", 20, 50), ("1", 305, 312), ("1,200", 395, 425), ("1,200", 470, 500)])
end = L(180, [("合", 20, 30), ("計", 35, 45), ("15,075", 470, 500)])
rows, ok = C.item_rows([hdr, r1, r2, r3, sh, end])
assert ok and len(rows) == 1, rows
r = rows[0]
assert (r["model_raw"], r["qty"], r["price"], r["amount"]) == ("B9565AW-T", 1, 13875, 13875), r
# 「単 価」が1字ずつ離れて読まれても、単価の列として扱う / 数字の行より下に型番がある書類(発注書)も、取れる
hdr2 = L(100, [("品名", 10, 50), ("数", 300, 310), ("量", 318, 328), ("単位", 350, 370), ("単", 400, 410), ("価", 418, 428), ("金", 470, 480), ("額", 488, 498)])
n1 = L(120, [("圧力計", 20, 70), ("2", 305, 312), ("個", 352, 362), ("10,875.00", 395, 440), ("21,750", 470, 500)])
n2 = L(130, [("AE20-133*0.6MPA", 20, 110)])
rows2, _ = C.item_rows([hdr2, n1, n2])
assert [(x["model_raw"], x["qty"], x["price"], x["amount"], x["unit"]) for x in rows2] == [("AE20-133", 2, 10875, 21750, "個")], rows2
print("qo_rows_test OK")
